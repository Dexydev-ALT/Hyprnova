std::string RescueBoot::report_path() const noexcept {
    return "/var/lib/hyprnova/rescue-report.json";
}

std::string RescueBoot::grub_snippet() const noexcept {
    const std::string iso = cfg_.boot_dir + "/rescue.iso";
    return std::format(R"GRUB(#!/bin/sh
# Generated by HyprNova Anti-Malware Sec (rescue module). Edits will be overwritten.
cat << 'EOF'
menuentry "{}" {{
    insmod loopback
    insmod iso9660
    set isofile="{}"
    loopback loop $isofile
    # Kernel/initrd paths differ between ISOs -- adjust the two lines below to
    # match the rescue image you supply. `rescue-prepare` stages the ISO there.
    linux (loop)/boot/vmlinuz boot=live quiet
    initrd (loop)/boot/initrd.img
}}
EOF
)GRUB",
                      cfg_.entry_title, iso);
}

std::string RescueBoot::clean_script() const noexcept {
    return R"SCRIPT(#!/bin/sh
# HyprNova rescue cleaner -- runs INSIDE the rescue environment (generated).
# The rescue ISO must ship clamav (Kaspersky-style rescue images do; a plain
# SystemRescue image works too after `pacman -Sy clamav`).
# Usage from the rescue shell:  sh /boot/hyprnova/clean.sh /mnt/realroot
set -u

REALROOT="${1:?usage: clean.sh /mnt/realroot}"
[ -d "$REALROOT/etc" ] || { echo "not a root filesystem: $REALROOT"; exit 2; }
mkdir -p "$REALROOT/var/lib/hyprnova"

echo "[rescue] scanning $REALROOT from outside the installed system"
REPORT="$REALROOT/var/lib/hyprnova/rescue-report.json"
FINDINGS="$REALROOT/var/lib/hyprnova/rescue-findings.txt"
: > "$FINDINGS"

if command -v clamscan >/dev/null 2>&1; then
    echo "[rescue] clamscan (fresh signatures) ..."
    clamscan -r --infected --suppress-ok-results \
        --exclude-dir='^/proc' --exclude-dir='^/sys' --exclude-dir='^/dev' \
        --log="$REALROOT/var/lib/hyprnova/rescue-clamav.log" "$REALROOT" \
        | tail -n 200
    grep -E 'FOUND$' "$REALROOT/var/lib/hyprnova/rescue-clamav.log" >> "$FINDINGS" 2>/dev/null
else
    echo "clamscan not available in the rescue image" >> "$FINDINGS"
fi

if command -v rkhunter >/dev/null 2>&1; then
    echo "[rescue] rkhunter against the mounted root ..."
    rkhunter --check --nocolors --rootdir "$REALROOT" --sk 2>&1 \
        | grep -E '^\[ Warning \]|^Warning:' >> "$FINDINGS" 2>/dev/null
fi

COUNT=$(wc -l < "$FINDINGS")
# findings as a JSON string array (backslash+quote escaped, POSIX awk)
FJSON=$(awk 'BEGIN{printf "["}
             NR>1{printf ","}
             {gsub(/\\/,"\\\\"); gsub(/"/,"\\\""); printf "\n  \"%s\"", $0}
             END{printf "\n]"}' "$FINDINGS")
cat > "$REPORT" << EOF
{
  "finished_epoch": $(date +%s),
  "root": "$REALROOT",
  "finding_count": $COUNT,
  "findings": $FJSON
}
EOF
echo "[rescue] done: $COUNT finding(s); report at $REPORT"
echo "[rescue] reboot back into your system and run: hyprnova-cli rescue-status"
)SCRIPT";
}

RescueBoot::Status RescueBoot::status() const noexcept {
    Status st;
    st.enabled = cfg_.enabled;
    st.iso_resolved = cfg_.iso_path;
    std::error_code ec;
    if (!cfg_.iso_path.empty()) {
        st.iso_found = fs::exists(cfg_.iso_path, ec) && fs::is_regular_file(cfg_.iso_path, ec);
    }
    st.iso_staged = core::fsx::is_file(cfg_.boot_dir + "/rescue.iso");
    st.grub_entry_present = core::fsx::is_file(cfg_.grub_entry_file);
    st.clean_script_present = core::fsx::is_file(cfg_.boot_dir + "/clean.sh");
    st.report_pending = core::fsx::is_file(report_path());
    st.prepared = st.iso_staged && st.grub_entry_present && st.clean_script_present;
    return st;
}

RescueBoot::Status RescueBoot::prepare(bool write) const noexcept {
    Status st = status();
    st.enabled = cfg_.enabled;

    // ---- blockers: every fact that stops the arm from being safe -----------
    if (!cfg_.enabled) st.blockers.push_back("rescue.enabled is false in agent.json");
    if (cfg_.iso_path.empty())
        st.blockers.push_back("rescue.iso_path is not configured (supply a rescue ISO)");
    else if (!st.iso_found)
        st.blockers.push_back(std::format("rescue ISO not found: {}", cfg_.iso_path));
    if (::geteuid() != 0)
        st.blockers.push_back("arming the rescue environment requires root");
    if (!core::fsx::is_dir("/boot"))
        st.blockers.push_back("/boot is not available (separate encrypted /boot? mount it first)");

    // The preview is ALWAYS produced: the operator reviews the exact bytes that
    // would land in the boot chain before any `write` is allowed.
    const std::string iso_for_grub =
        cfg_.boot_dir + "/rescue.iso";
    st.preview = std::format(
        "=== {}{} ===\n{}\n=== {} ===\n{}",
        write ? "WRITTEN" : "PREVIEW (dry run)",
        st.blockers.empty() ? "" : " -- blocked, nothing written",
        grub_snippet(),
        std::format("{} (mode 0755)", cfg_.boot_dir + "/clean.sh"),
        clean_script());

    if (write && st.blockers.empty()) {
        std::error_code ec;
        // 1. stage the ISO
        if (!st.iso_staged) {
            fs::create_directories(cfg_.boot_dir, ec);
            if (ec) {
                st.blockers.push_back(std::format("cannot create {}: {}", cfg_.boot_dir, ec.message()));
                return st;
            }
            fs::copy_file(cfg_.iso_path, iso_for_grub, fs::copy_options::overwrite_existing, ec);
            if (ec) {
                st.blockers.push_back(std::format("copying the ISO failed: {}", ec.message()));
                return st;
            }
            st.iso_staged = true;
        }
        // 2. GRUB entry (0700: grub.d scripts are executed by grub-mkconfig)
        if (core::fsx::mkdir_p(fs::path(cfg_.grub_entry_file).parent_path().string(), 0755)) {
            std::ofstream out{cfg_.grub_entry_file, std::ios::binary | std::ios::trunc};
            out << grub_snippet();
            out.close();
            static_cast<void>(core::fsx::set_mode(cfg_.grub_entry_file, 0700));
            st.grub_entry_present = core::fsx::is_file(cfg_.grub_entry_file);
        }
        // 3. clean script into the staged boot area
        {
            std::ofstream out{cfg_.boot_dir + "/clean.sh", std::ios::binary | std::ios::trunc};
            out << clean_script();
            out.close();
            static_cast<void>(core::fsx::set_mode(cfg_.boot_dir + "/clean.sh", 0755));
            st.clean_script_present = core::fsx::is_file(cfg_.boot_dir + "/clean.sh");
        }
        st.prepared = st.iso_staged && st.grub_entry_present && st.clean_script_present;
        SINFO("rescue", "rescue environment armed: ISO staged, GRUB entry + clean script written{}",
              "");
    }
    return st;
}

bool RescueBoot::boot(bool boot_once, std::string& err) const noexcept {
    const Status st = status();
    if (!st.prepared) {
        err = "not prepared yet: run `rescue-prepare --write` first";
        return false;
    }
    if (::geteuid() != 0) {
        err = "booting into the rescue environment requires root";
        return false;
    }
    const std::string grub_reboot =
        core::exec::find_in_system_path("grub-reboot");
    if (boot_once && grub_reboot.empty()) {
        err = "grub-reboot not found (GRUB 2 required for boot-once; "
              "or set rescue.auto_reboot and select the entry manually)";
        return false;
    }
    // The entry lives in the generated file; GRUB addresses it by title.
    if (boot_once) {
        const auto r = core::exec::run(grub_reboot, {cfg_.entry_title}, {});
        if (!r.ok()) {
            err = std::format("grub-reboot failed: {}",
                              r.err.empty() ? r.out : r.err);
            return false;
        }
    }
    const std::string reboot = core::exec::find_in_system_path("systemctl");
    if (reboot.empty()) {
        err = "systemctl not found; reboot manually now";
        return false;
    }
    SWARN("rescue", "REBOOTING into the rescue environment (operator requested)");
    const auto r2 = core::exec::run(reboot, {"reboot"}, {});
    if (!r2.ok()) {
        err = "systemctl reboot failed";
        return false;
    }
    return true;
}

